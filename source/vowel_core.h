// Cycles one vowel_block takes on the unit at most: an estimate from counting the instructions the unit's compiler
// makes of this code (build/COST.md: about 22,900 instructions a block, 23,700 to 27,500 cycles), not a measurement
// on a unit. Declared above the high estimate; above the 25,000 the design aimed at (the full-precision input and the
// rounded low state cost about 3,100 instructions a block).
enum { VOWEL_COST = 29000 };
#define VOWEL_DEFAULTS { 32767, 16384, 6000, 26000, 16384, 16384, 0, 0 }
static_assert(VOWEL_KNEE == 3 << 26, "the saturator's code assumes the knee at 0.75 (4 (1 - K) = 1)");

// Everything an instance needs. All zero is a valid fresh state: the first block takes its targets at once.
struct VowelState {
    int low[2][3], band[2][3];   // the filters, per side and formant: Q28 full scale, held within +-2^29
    int fc[3], qc[3], gc[3];     // the coefficients now (f, damping, signed level times gain / 32): Q15 << 8
    int mix;                     // MIX now, Q15 << 8
    int lf[3], lq[3], lv[3];     // the smoothed targets: centre (Q12 octaves above 100 Hz), damping (Q12 log2), level (Q15)
    int f1, f2;                  // F1 and F2 as sounding, before SHIFT, smoothed: for vowel_open and vowel_wide
    int env;                     // the envelope follower of the dry's block peak (MOTION), Q30 of full scale
    int gain;                    // the last block's gain word: base make-up * the trim's limit (2) * LEVEL / 32, Q15 (2048,
                                 // 8192, 32767 at LEVEL 0, 16384, 32767); for the tests: it follows value word 5 alone
    unsigned phase;              // the tempo sweep's phase, a full turn = 2^32
    int pos, open;               // the vowel position (0..32767) and the pull towards "a" (Q15) of the last block
    unsigned ready;              // 0 until the first block
    int acc[64];                 // scratch of one block: one side's wet sum (no meaning between blocks)
    short co[3][8][3];           // scratch of one block: each formant's f, damping, level for each step of eight samples
    short mix8[8];               // scratch of one block: MIX for each step
};

static inline int vowel_mul15(int x, int q) { return (x >> 15) * q + (((x & 0x7fff) * q) >> 15); }   // x * q / 2^15, q 0..32767
// the same for |x| < 2^30 and |q| <= 32767, in two 16x16 products (x >> 15 then fits a short): what the loops use.
// The top part is taken from the unsigned shift: the same low 16 bits, but the unit's compiler then cannot see that
// the value fits a short and drop the cast, which made it use a 32-bit multiply (several cycles) where the range of
// x was known. (The conversion to short keeps the low 16 bits: GCC's definition.)
static inline int vowel_hi15(int x) { return (int)(short)((unsigned)x >> 15); }
static inline int vowel_mul15s(int x, int q) {
    return vowel_hi15(x) * (int)(short)q + (((int)(short)(x & 0x7fff) * (int)(short)q) >> 15);
}
// the same rounded to nearest (the low part's product plus half before its shift): for the low state's update, whose
// rounding error would otherwise have a mean of -1/2 a sample, which the filter turns into a standing offset of the
// band output (-1/2 / f: up to some 60 steps, a residual of about -119 dBFS on digital silence, and a DC that limited a
// quiet signal's signal-to-noise)
static inline int vowel_mul15r(int x, int q) {
    return vowel_hi15(x) * (int)(short)q + (((int)(short)(x & 0x7fff) * (int)(short)q + 16384) >> 15);
}
static inline int vowel_clamp(int v, int lo, int hi) { return v < lo ? lo : v > hi ? hi : v; }
static inline int vowel_min(int a, int b) { return a < b ? a : b; }
static inline int vowel_max(int a, int b) { return a > b ? a : b; }
static inline int vowel_step(int d) { return d >= 0 ? d >> 3 : -((-d) >> 3); }                       // d / 8 towards zero
static inline int vowel_lerp(int a, int b, int fr) { return a + (((b - a) * fr) >> 15); }             // fr Q15, 0..32768

static inline unsigned vowel_open(const VowelState* s) {     // 0..32767: how open the mouth is now (F1, i .. a)
    return (unsigned)vowel_clamp(((s->f1 - VOWEL_OPEN_LO) * VOWEL_OPEN_K) >> 12, 0, 32767);
}
static inline unsigned vowel_wide(const VowelState* s) {     // 0..32767: how wide the mouth is now (F2, u .. i)
    return (unsigned)vowel_clamp(((s->f2 - VOWEL_WIDE_LO) * VOWEL_WIDE_K) >> 12, 0, 32767);
}

// After a gap in the blocks (the train skips the effects while the instrument is silent): forget the sound that was
// cut off, so the next note starts with a closed mouth and no old ringing. Only the filters and the envelope are
// cleared: the values, the smoothed targets and the sweep's phase stay. The pack calls it before vowel_block when it
// saw a gap.
static inline void vowel_gap(VowelState* s) {
    for (int c = 0; c < 2; ++c) for (int k = 0; k < 3; ++k) { s->low[c][k] = 0; s->band[c][k] = 0; }
    s->env = 0;
}

// One formant on one side's 64 samples, in eight steps of eight samples, each step with its own coefficients
// (co: f, damping, signed level, Q15, for each step: worked out once a block for both sides). The input is the dry at
// full precision times the level: (x >> 2) * g / 2^15 in two 16x16 products, with g = level * gain / 32, which is the
// dry times level * gain / 16 in Q28 (the scale the top 16 bits times gain / 16 had before, without their rounding).
// add 0: the band output is written to acc, 1: added. The function is inlined three times with add constant.
// The ranges (LIM = 2^29; every vowel_mul15s call needs |x| < 2^30):
//   |bd| <= LIM, f <= 32518                         -> |lo + bd f| < 2^30, then held (rounded to nearest: vowel_mul15r)
//   |x >> 2| <= 2^29, |g| <= 32767                 -> |xg| <= 2^29 - 2^14 + 1
//   |xg - bd| <= 2^30 - 2^14 + 1 < 2^30, q <= 16383 -> |(xg - bd) q| < 2^29 - 2^14, so |hi| < 2^30 - 2^14
//   |hi| < 2^30                                     -> |bd + hi f| < 2^29 + 2^30, then held; |sum of 3| <= 1.5 * 2^30
static inline void vowel_formant(int* lo_s, int* bd_s, const int* x, int* acc, const short* co, int add) {
    const int LIM = 1 << 29;
    int lo = *lo_s, bd = *bd_s;
    for (int j = 0; j < 8; ++j, co += 3, x += 8, acc += 8) {
        const int f = co[0], q = co[1], g = co[2];
        for (int i = 0; i < 8; ++i) {
            lo = vowel_clamp(lo + vowel_mul15r(bd, f), -LIM, LIM);   // first: the unit's compiler then keeps its
            const int xg = vowel_mul15s(x[i] >> 2, g);                 // constants in registers (40 instructions, not 45)
            const int hi = vowel_mul15s(xg - bd, q) - lo;
            bd = vowel_clamp(bd + vowel_mul15s(hi, f), -LIM, LIM);
            acc[i] = add ? acc[i] + bd : bd;
        }
    }
    *lo_s = lo; *bd_s = bd;
}

static void vowel_block(VowelState* s, int* left, int* right, const volatile unsigned* params, unsigned bpm_q8) {
    int p[6];
    for (int k = 0; k < 6; ++k) { const unsigned v = params[k] >> 16; p[k] = v > 32767u ? 32767 : (int)v; }

    // the envelope: the block's peak, a fast rise, a fall of VF_RELEASE_S
    int peak = 0;
    for (int i = 0; i < 64; ++i) {
        int a = left[i] >> 1; if (a < 0) a = -a; if (a > peak) peak = a;
        a = right[i] >> 1; if (a < 0) a = -a; if (a > peak) peak = a;
    }
    if (peak > s->env) s->env += vowel_mul15(peak - s->env, VOWEL_ATTACK);
    else s->env -= vowel_mul15(s->env, VOWEL_RELEASE);

    // MOTION: the pull towards "a", or the sweep
    int pos = p[0], open = 0;
    if (p[2] < 16384 - VOWEL_DEAD) {
        const int amount = ((16384 - VOWEL_DEAD - p[2]) * VOWEL_AMOUNT_K) >> 10;       // Q15
        open = vowel_mul15(s->env >> 15, amount) << VOWEL_SENS;
        if (open > 32767) open = 32767;
    } else if (p[2] > 16384 + VOWEL_DEAD) {
        unsigned bpm = bpm_q8 ? bpm_q8 : 30720u;                                          // unknown: 120
        bpm = bpm < 5120u ? 5120u : bpm > 102400u ? 102400u : bpm;                        // 20 .. 400
        const unsigned inc = bpm * (unsigned)VOWEL_INC_INT + ((bpm * (unsigned)VOWEL_INC_FRAC) >> 16);   // a whole note
        const int z = p[2] - (16384 + VOWEL_DEAD), w = VOWEL_ZONE;                            // five zones
        const int zone = z < w ? 0 : z < 2 * w ? 1 : z < 3 * w ? 2 : z < 4 * w ? 3 : 4;
        s->phase += inc << zone;
        const int ph = (int)(s->phase >> 16);
        int m = ph < 32768 ? ph * 2 - 32767 : (65535 - ph) * 2 - 32767;                  // a triangle, |m| <= 32767
        m = ((m >> 1) * (98304 - ((m * m) >> 15))) >> 15;                                  // towards a sine: |product| < 2^30
        pos += (m * VOWEL_DEPTH) >> 15;
        if (pos < 0) pos = -pos;
        if (pos > 32767) pos = 65534 - pos;
    }
    s->pos = pos; s->open = open;

    // the wet gain / 32 (Q15): the base make-up times LEVEL, 2^((p[5] - 32767) / 8192) (4 octaves down to LEVEL 0),
    // times VOWEL_GAINK (the base times the trim's limit / 8: 1 for +12 dB and 2). It follows the value word only.
    const int fresh = s->ready == 0;
    const int a5 = (32767 - p[5]) >> 1, j5 = (a5 & 4095) >> 6, r5 = a5 & 63;                // Q12 octaves, 0..16383
    const int gn = vowel_mul15((VOWEL_EXP2[j5] + (((VOWEL_EXP2[j5 + 1] - VOWEL_EXP2[j5]) * r5) >> 6)) >> (a5 >> 12), VOWEL_GAINK);
    s->gain = gn;

    // the vowel at pos, pulled towards "a" by open
    int seg = pos >> 13; if (seg > 3) seg = 3;
    const int fr = pos >= 32767 ? 32768 : (pos - (seg << 13)) << 2;
    const int shift = (p[1] - 16384) >> 2;                                                // Q12 octaves
    const int res = p[4] < 16384 ? ((16384 - p[4]) * VOWEL_RES_WIDE) >> 10 : -(((p[4] - 16384) * VOWEL_RES_NARROW) >> 10);
    int ft[3], qt[3], gt[3];
    for (int k = 0; k < 3; ++k) {
        int lf = vowel_lerp(VOWEL_LF[seg][k], VOWEL_LF[seg + 1][k], fr);
        int lq = vowel_lerp(VOWEL_LQ[seg][k], VOWEL_LQ[seg + 1][k], fr);
        int lv = vowel_lerp(VOWEL_LV[seg][k], VOWEL_LV[seg + 1][k], fr);
        if (open) { lf = vowel_lerp(lf, VOWEL_LF[0][k], open); lq = vowel_lerp(lq, VOWEL_LQ[0][k], open); lv = vowel_lerp(lv, VOWEL_LV[0][k], open); }
        if (k == 0) s->f1 = fresh ? lf : s->f1 + vowel_mul15(lf - s->f1, VOWEL_SMOOTH);
        if (k == 1) s->f2 = fresh ? lf : s->f2 + vowel_mul15(lf - s->f2, VOWEL_SMOOTH);
        lf = vowel_clamp(lf + shift, 0, VOWEL_LF_MAX);
        lq = vowel_clamp(lq + res, -8 * 4096, -4096);
        if (fresh) { s->lf[k] = lf; s->lq[k] = lq; s->lv[k] = lv; }
        else { s->lf[k] += vowel_mul15(lf - s->lf[k], VOWEL_SMOOTH); s->lq[k] += vowel_mul15(lq - s->lq[k], VOWEL_SMOOTH); s->lv[k] += vowel_mul15(lv - s->lv[k], VOWEL_SMOOTH); }
        // f from the table over log frequency
        const int i = s->lf[k] >> 8, f8 = s->lf[k] & 255;
        ft[k] = (VOWEL_FTAB[i] + (((VOWEL_FTAB[i + 1] - VOWEL_FTAB[i]) * f8) >> 8)) << 8;
        // damping = 2^lq: whole octaves by a shift, the rest from the table
        const int a = -s->lq[k], j = (a & 4095) >> 6, j6 = a & 63;
        const int q = (VOWEL_EXP2[j] + (((VOWEL_EXP2[j + 1] - VOWEL_EXP2[j]) * j6) >> 6)) >> (a >> 12);
        qt[k] = vowel_clamp(q, VOWEL_QMIN, VOWEL_QMAX) << 8;
        gt[k] = vowel_mul15(s->lv[k], gn) << 8;                                 // level * trim / 2 * gain / 16 = level * trim * gain / 32
    }
    gt[0] *= VOWEL_SIGN1; gt[1] *= VOWEL_SIGN2; gt[2] *= VOWEL_SIGN3;
    const int mt = p[3] << 8;

    if (fresh) { for (int k = 0; k < 3; ++k) { s->fc[k] = ft[k]; s->qc[k] = qt[k]; s->gc[k] = gt[k]; } s->mix = mt; s->ready = 1; }

    // the ramps across the block: eight steps of eight samples, each step an eighth of the way (towards zero, so
    // they never pass their targets); the last step lands on the targets. Worked out once for both sides.
    short* co = &s->co[0][0][0];
    for (int k = 0; k < 3; ++k) {
        const int c[3] = { s->fc[k], s->qc[k], s->gc[k] }, t[3] = { ft[k], qt[k], gt[k] };
        for (int n = 0; n < 3; ++n) {
            const int d = vowel_step(t[n] - c[n]); int v = c[n];
            for (int j = 0; j < 8; ++j) { v = j < 7 ? v + d : t[n]; s->co[k][j][n] = (short)(v >> 8); }
        }
    }
    {
        const int dm = vowel_step(mt - s->mix); int mc = s->mix;
        for (int j = 0; j < 8; ++j) { mc = j < 7 ? mc + dm : mt; s->mix8[j] = (short)(mc >> 8); }
    }

    int* acc = s->acc;
    for (int ch = 0; ch < 2; ++ch) {
        int* io = ch ? right : left;
        vowel_formant(&s->low[ch][0], &s->band[ch][0], io, acc, co, 0);
        vowel_formant(&s->low[ch][1], &s->band[ch][1], io, acc, co + 24, 1);
        vowel_formant(&s->low[ch][2], &s->band[ch][2], io, acc, co + 48, 1);
        for (int j = 0; j < 8; ++j) {
            const int m = s->mix8[j];
            for (int i = j * 8; i < j * 8 + 8; ++i) {
                const int a = acc[i], dry = io[i];
                // the sum is wet / 16, so Q24 of the wet. The soft saturator on |wet|: up to the knee as it is, above
                // it K + d - d^2, full scale from 1.25 on (the rare case is the branch: the usual one runs straight)
                const int sg = a >> 31; int y = (a ^ sg) - sg;                                      // |a| < 1.5 * 2^30
                if (y > (VOWEL_KNEE >> 4)) {
                    const int dk = vowel_min(y - (VOWEL_KNEE >> 4), (1 << 23) - 1), d15 = dk >> 8;  // 0..0.5, 0..32767
                    y = vowel_min((VOWEL_KNEE >> 4) + dk - ((d15 * d15) >> 8), (1 << 24) - 1);      // d15 rounds down:
                }                                                                                   // y can pass by 255
                const int wet = ((y ^ sg) - sg) * 32;                                               // Q29, the sign back
                // dry + (wet - dry) * MIX in Q29, then the dry's two lowest bits back: MIX 0 gives the dry unchanged
                const int h = dry >> 2;
                // |wet - h| < 2^30. out lies between h and wet (the product rounds towards wet's side or h's, never
                // past either), so it stays in -2^29 .. 2^29 - 1 with no clamp: |wet| <= 2^29 - 32
                const int out = h + vowel_mul15s(wet - h, m);
                io[i] = (int)(((unsigned)out << 2) | ((unsigned)dry & 3u));
            }
        }
    }
    // digital silence (the block's dry peak 0): a formant whose states are both small is set to 0. Without it, the
    // rounding of the state products can keep a tiny limit cycle running forever (review 3: F3 at RES max, about +-80
    // steps, -105.7 dBFS). 1024 steps of Q28 is -84 dBFS of wet at most, reached only on a tail already fallen that far.
    if (peak == 0)
        for (int c = 0; c < 2; ++c) for (int k = 0; k < 3; ++k)
            if ((unsigned)(s->low[c][k] + 1023) < 2047u && (unsigned)(s->band[c][k] + 1023) < 2047u) { s->low[c][k] = 0; s->band[c][k] = 0; }
    for (int k = 0; k < 3; ++k) { s->fc[k] = ft[k]; s->qc[k] = qt[k]; s->gc[k] = gt[k]; }
    s->mix = mt;
}

